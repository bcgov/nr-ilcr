-- Undoes usr/user-admin-anchors.sql exactly: the ten dedicated mills (26064-26073) and every user
-- under the E2E_SEED_USRADM sentinel, plus the two accounts the S11/S12 first-time imports provision
-- (...13, ...14), which carry the acting admin's id rather than the sentinel. Children first.

SET DEFINE OFF

DECLARE
  c_user CONSTANT VARCHAR2(30) := 'E2E_SEED_USRADM';
BEGIN
  DELETE FROM THE.ILCR_MILL_USER_XREF     WHERE ILCR_MILL_ID BETWEEN 26064 AND 26073;
  DELETE FROM THE.ILCR_MILL_REPORT_STATUS WHERE ILCR_MILL_ID BETWEEN 26064 AND 26073;
  DELETE FROM THE.ILCR_MILL_STATUS_XREF   WHERE ILCR_MILL_STATUS_XREF_ID BETWEEN 26064 AND 26073;
  DELETE FROM THE.MILL
   WHERE ENTRY_USERID = c_user AND MILL_ID BETWEEN 26064 AND 26073;
  DELETE FROM THE.ILCR_USER u
   WHERE (u.ENTRY_USERID = c_user
          OR u.USER_GUID IN ('E2E00000000000000000000000000013', 'E2E00000000000000000000000000014'))
     AND NOT EXISTS (SELECT 1 FROM THE.ILCR_MILL_USER_XREF x WHERE x.USER_GUID = u.USER_GUID);
  COMMIT;
END;
